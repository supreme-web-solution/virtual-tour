export function glyphFor(
    kind: HotspotType | 'draft',
    chosen?: string | null,
): PinGlyph {
    if (kind === 'draft') {
        return 'plus';
    }

    return chosen &&
        (GLYPHS_BY_TYPE[kind] as string[]).includes(chosen) &&
        chosen in GLYPHS
        ? (chosen as PinGlyph)
        : GLYPHS_BY_TYPE[kind][0];
}

